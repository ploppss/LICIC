public class EjemploHibrido {
    public static void main(String[] args) {
        System.out.println("Hola, Mundo desde java!");
    }
}

// --- INSTRUCCIONES DE INSTALACIÓN ---
// 1. Instala el Java Development Kit (JDK) (Se recomienda una versión LTS como
// JDK 21 o superior):
// https://www.oracle.com/java/technologies/downloads/
// 2. Verifica la instalación con: java --version y javac --version en la
// terminal.
// 3. Configura las variables de entorno:
// - Crea una variable JAVA_HOME que apunte a la ruta del JDK: C:\Program
// Files\Java\jdk-21 (o la versión instalada).
// - Agrega %JAVA_HOME%\bin a la variable de entorno PATH de tu sistema.
// 4. Instala la extensión "Extension Pack for Java" de Microsoft en VS Code.

// --- TERMINAL ---
// 1. Compilar (Genera el bytecode .class): javac EjemploHibrido.java
// 2. Ejecutar (La JVM interpreta y ejecuta el bytecode): java EjemploHibrido
// Salida esperada: Hola, Mundo desde java!